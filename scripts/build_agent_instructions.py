"""Build CLAUDE.md and AGENTS.md from the shared role sources.

The researcher and reviewer role text lives once in docs/agent-roles/. This
script fills in the agent names for each configuration so the two instruction
files cannot drift apart. Edit the role sources, then run:

    python scripts/build_agent_instructions.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROLES = ROOT / "docs" / "agent-roles"

HEADER = """<!-- Generated by scripts/build_agent_instructions.py from docs/agent-roles/.
Edit the role sources there, not this file. -->

# {AGENT} Workflow Instructions

Read `WORKFLOW-CONFIG.md` first to determine your role for this session.

- **Config A** → your role is **{ROLE_A}**. Follow the [{ROLE_A}](#role-{ANCHOR_A}-config-a) section.
- **Config B** → your role is **{ROLE_B}**. Follow the [{ROLE_B}](#role-{ANCHOR_B}-config-b) section.

---

"""

# Config A: Codex researches, Claude Code reviews. Config B: the reverse.
FILES = {
    "AGENTS.md": {
        "agent": "Codex",
        "sections": [("researcher", "A"), ("reviewer", "B")],
    },
    "CLAUDE.md": {
        "agent": "Claude Code",
        "sections": [("reviewer", "A"), ("researcher", "B")],
    },
}

RESEARCHER_BY_CONFIG = {"A": "Codex", "B": "Claude Code"}
REVIEWER_BY_CONFIG = {"A": "Claude Code", "B": "Codex"}


def render(role: str, config: str, self_file: str) -> str:
    text = (ROLES / f"{role}-role.md").read_text(encoding="utf-8")
    return (
        text.replace("{CONFIG}", config)
        .replace("{RESEARCHER}", RESEARCHER_BY_CONFIG[config])
        .replace("{REVIEWER}", REVIEWER_BY_CONFIG[config])
        .replace("{SELF_FILE}", self_file)
    )


def main() -> None:
    for name, spec in FILES.items():
        (role_a, _), (role_b, _) = spec["sections"]
        header = HEADER.format(
            AGENT=spec["agent"],
            ROLE_A=role_a.capitalize(),
            ROLE_B=role_b.capitalize(),
            ANCHOR_A=role_a,
            ANCHOR_B=role_b,
        )
        body = "\n---\n\n".join(render(role, config, name) for role, config in spec["sections"])
        (ROOT / name).write_text(header + body, encoding="utf-8", newline="\n")
        print(f"wrote {name}")


if __name__ == "__main__":
    main()
