"""Build the per-runtime instruction files from the shared role sources.

Different agent runtimes auto-load different file names (Claude Code reads
CLAUDE.md, Codex and many other agents read AGENTS.md, Gemini CLI reads
GEMINI.md). They all get the same content, generated from docs/agent-roles/,
so no runtime is special. Edit the role sources, then run:

    python scripts/build_agent_instructions.py
"""

from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROLES = ROOT / "docs" / "agent-roles"
TARGETS = {"CLAUDE.md": "Claude Code", "AGENTS.md": "Codex and other AGENTS.md-aware agents", "GEMINI.md": "Gemini CLI"}

HEADER = """<!-- Generated by scripts/build_agent_instructions.py from docs/agent-roles/.
Edit the role sources there, not this file. CLAUDE.md, AGENTS.md, and GEMINI.md
are identical apart from this header. -->

# Agent Instructions: Human–AI Collaborative Science Framework

This file is loaded automatically by {RUNTIME}. Any agent can act as the
**researcher** or the **reviewer**; the framework does not depend on which
product you are.

## Which role are you?

1. If your prompt says you were started by the workflow orchestrator, it names
   your role. Follow that role's section below.
2. Otherwise, if the user tells you your role, follow it.
3. Otherwise, read `roles` in `workflow.config.json`, tell the user which role
   it assigns to you, and ask them to confirm before starting.

Then follow the matching section: [Researcher](#role-researcher) or
[Reviewer](#role-reviewer).

---

"""


def main() -> None:
    body = "\n---\n\n".join(
        (ROLES / f"{role}-role.md").read_text(encoding="utf-8") for role in ("researcher", "reviewer")
    )
    for name, runtime in TARGETS.items():
        (ROOT / name).write_text(HEADER.replace("{RUNTIME}", runtime) + body, encoding="utf-8", newline="\n")
        print(f"wrote {name}")


if __name__ == "__main__":
    main()
